        <h1>HTML Basic</h1>
        <p>HTML (HyperText Markup Language) is the standard language for creating web pages. Below are some basic elements used in HTML:</p>

        <h2>1. Basic Structure</h2>
        <code>
&lt;!DOCTYPE html&gt;
&lt;html&gt;
  &lt;head&gt;
    &lt;title&gt;Page Title&lt;/title&gt;
  &lt;/head&gt;
  &lt;body&gt;
    &lt;h1&gt;Hello, World!&lt;/h1&gt;
    &lt;p&gt;This is a paragraph.&lt;/p&gt;
  &lt;/body&gt;
&lt;/html&gt;
        </code>

        <h2>2. Common HTML Elements</h2>
        <ul>
            <li><strong>&lt;h1&gt; to &lt;h6&gt;</strong> — Headings</li>
            <li><strong>&lt;p&gt;</strong> — Paragraphs</li>
            <li><strong>&lt;a&gt;</strong> — Links</li>
            <li><strong>&lt;img&gt;</strong> — Images</li>
            <li><strong>&lt;ul&gt;, &lt;ol&gt;, &lt;li&gt;</strong> — Lists</li>
            <li><strong>&lt;div&gt;, &lt;span&gt;</strong> — Containers</li>
        </ul>

        <h2>3. Example: Link and Image</h2>
        <code>
&lt;a href="https://www.example.com"&gt;Visit Example&lt;/a&gt;
&lt;img src="image.jpg" alt="Example Image" width="200"&gt;
        </code>
